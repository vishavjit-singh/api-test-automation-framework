    """Fault injection on the service; skipped on targets without test hooks. Always resets afterwards."""
    if not env.test_hooks:
        pytest.skip(f"{env.name} has no test hooks")

    def set_carrier(mode: str):
        r = admin.put("/_test/faults", json={"carrier": mode})
        assert r.status_code == 200, r.text
        return r.json()

    def status():
        return admin.get("/_test/faults").json()

    set_carrier.status = status
    admin.delete("/_test/faults")
    yield set_carrier
    admin.delete("/_test/faults")      # healthy carrier, counters cleared, breaker closed


