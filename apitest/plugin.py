import time
from pathlib import Path

import pytest

from .auth import ALL_ROLES, TokenFactory
from .client import ApiClient, Recorder, build_transport_client
from .config import load_environment
from .xray import build_execution, load_mapping

TIERS = ("positive", "negative", "edge", "fallback")
CASE_RX = re.compile(r"^API-TC-\d{3}$")


def pytest_addoption(parser):
    g = parser.getgroup("apitest")
    g.addoption("--env", default=None, help="target environment from config/environments.yaml (default: API_ENV "
                "or inproc)")
    g.addoption("--reports-dir", default="reports", help="where results.json, requests.jsonl and Xray JSON go")
    g.addoption("--xray-mapping", default="xray/mapping.yaml")
    g.addoption("--xray-flavor", choices=["cloud", "server"], default="cloud")
    g.addoption("--xray-strict", action="store_true", help="fail the run if a case has no Xray mapping")
    g.addoption("--catalogue", default=None, help="write a Markdown test catalogue for the collected cases")


def pytest_configure(config):
    config.addinivalue_line("markers", "case(id): stable test-case ID (API-TC-###) mapped to an Xray test issue")
    config.addinivalue_line("markers", "known_defect(key, summary): expected failure linked to a defect issue")
    config.addinivalue_line("markers", "smoke: minimal set for a post-deploy check")
    for t in TIERS:
        config.addinivalue_line("markers", f"{t}: {t} test tier")
    config._apitest = {"results": [], "recorder": None, "started": time.time()}


# ------------------------------------------------------------------------------------- collection
def _case(item) -> str | None:
    m = item.get_closest_marker("case")
    return m.args[0] if m else None


def pytest_collection_modifyitems(session, config, items):
    owners: dict[str, str] = {}
    problems = []
    for item in items:
        if "tests/api" not in str(item.fspath).replace("\\", "/"):
            continue
        case = _case(item)
        func = f"{item.module.__name__}::{getattr(item, 'originalname', item.name)}"
        if not case:
            problems.append(f"{item.nodeid}: missing @pytest.mark.case")
            continue
        if not CASE_RX.match(case):
            problems.append(f"{item.nodeid}: case id {case!r} must look like API-TC-001")
        if owners.setdefault(case, func) != func:
            problems.append(f"{case} is used by both {owners[case]} and {func}")
        if not any(item.get_closest_marker(t) for t in TIERS):
            problems.append(f"{item.nodeid}: no tier marker ({', '.join(TIERS)})")
        d = item.get_closest_marker("known_defect")
        if d:
            item.add_marker(pytest.mark.xfail(strict=True, reason=f"{d.args[0]}: {d.args[1]}"))
    if problems:
        raise pytest.UsageError("test-case metadata problems:\n  " + "\n  ".join(problems))
    path = config.getoption("catalogue")
    if path:
        _write_catalogue(Path(path), [i for i in items if _case(i)], config)


def _write_catalogue(path: Path, items, config) -> None:
    mapping = load_mapping(config.getoption("xray_mapping"))["cases"]
    rows, seen = [], set()
    for item in sorted(items, key=_case):
        case = _case(item)
        if case in seen:
            continue
        seen.add(case)
        tiers = ", ".join(t for t in TIERS if item.get_closest_marker(t))
        doc = (item.function.__doc__ or "").strip().splitlines()[0] if item.function.__doc__ else item.name
        d = item.get_closest_marker("known_defect")
        note = f" · known defect {d.args[0]}" if d else ""
        key = mapping.get(case, {}).get("key", "—")
        rows.append(f"| {case} | {key} | {tiers}{' · smoke' if item.get_closest_marker('smoke') else ''} | "
                    f"{doc}{note} |")
    tier_counts = {t: sum(1 for i in items if i.get_closest_marker(t) and _case(i)) for t in TIERS}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# Test catalogue\n\nGenerated by `make catalogue` from the test code (case markers and "
                    "docstrings); do not edit by hand.\n\n"
                    f"{len(rows)} cases, {len(items)} pytest items (parametrised cases count once per parameter). "
                    "Items per tier: " + ", ".join(f"{k} {v}" for k, v in tier_counts.items()) + ".\n\n"
                    "| Case | Xray key | Tier | What it checks |\n|---|---|---|---|\n" + "\n".join(rows) + "\n")


