@pytest.fixture(autouse=True)
def _apitest_track(request):
    """Tag recorded HTTP calls with the running test (after session fixtures exist)."""
    rec = request.config._apitest.get("recorder")
    if rec is not None:
        rec.current_test = request.node.nodeid
    yield
    if rec is not None:
        rec.current_test = None


@pytest.hookimpl(wrapper=True)
def pytest_runtest_makereport(item, call):
    rep = yield
    if call.when == "setup":
        item._apitest_start = call.start
    item.__dict__.setdefault("_apitest_reports", []).append(rep)
    return rep


@pytest.hookimpl(wrapper=True)
def pytest_runtest_protocol(item, nextitem):
    item._apitest_reports = []
    res = yield
    _record(item)
    return res


def _record(item) -> None:
    case = _case(item)
    if not case:
        return
    reports = item._apitest_reports
    outcome, message = "passed", ""
    for r in reports:
        if r.failed:
            outcome, message = "failed", str(r.longrepr).splitlines()[-1][:300] if r.longrepr else ""
            break
        if r.skipped and hasattr(r, "wasxfail"):
            outcome, message = "xfailed", r.wasxfail
            break
        if r.skipped:
            outcome = "skipped"
            message = r.longrepr[2] if isinstance(r.longrepr, tuple) else ""
            break
        if r.when == "call" and hasattr(r, "wasxfail"):
            outcome, message = "xpassed", r.wasxfail
    d = item.get_closest_marker("known_defect")
    callspec = getattr(item, "callspec", None)
    doc = (item.function.__doc__ or "").strip().splitlines()[0] if getattr(item, "function", None) and \
        item.function.__doc__ else item.name
    item.config._apitest["results"].append({
        "case": case, "nodeid": item.nodeid, "param": callspec.id if callspec else None, "title": doc,
        "tiers": [t for t in TIERS if item.get_closest_marker(t)], "smoke": bool(item.get_closest_marker("smoke")),
        "outcome": outcome, "message": message, "defects": [d.args[0]] if d else [],
        "start": getattr(item, "_apitest_start", time.time()), "finish": time.time(),
        "duration_s": round(sum(r.duration for r in reports), 4),
    })


def pytest_sessionfinish(session, exitstatus):
    state = session.config._apitest
    results = state["results"]
    if not results or session.config.getoption("collectonly"):
        return
    out = Path(session.config.getoption("reports_dir"))
    out.mkdir(parents=True, exist_ok=True)
    env = state.get("env", session.config.getoption("env") or "inproc")
    (out / "results.json").write_text(json.dumps({"environment": env, "results": results}, indent=1))
    rec = state.get("recorder")
    if rec is not None:
        (out / "requests.jsonl").write_text("".join(json.dumps(c) + "\n" for c in rec.calls))
    mapping = load_mapping(session.config.getoption("xray_mapping"))
    execution, unmapped = build_execution(results, mapping, env, session.config.getoption("xray_flavor"))
    (out / "xray-results.json").write_text(json.dumps(execution, indent=2))
    tr = session.config.pluginmanager.get_plugin("terminalreporter")
    if tr:
        tr.ensure_newline()
        tr.write_line(f"apitest: {len(execution['tests'])} Xray results → {out / 'xray-results.json'}"
                      + (f" · unmapped cases: {', '.join(unmapped)}" if unmapped else ""))
    if unmapped and session.config.getoption("xray_strict"):
        session.exitstatus = pytest.ExitCode.TESTS_FAILED
